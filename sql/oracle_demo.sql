-- Contrato demostrativo, no es el procedimiento real de ADEA.
-- Crear solo en esquema / ambiente de PRUEBAS con autorización.
CREATE TABLE INE_EXPEDIENTES_DEMO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CURP VARCHAR2(18) NOT NULL,
    CLAVE_ELECTOR VARCHAR2(18) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(80),
    APELLIDO_MATERNO VARCHAR2(80),
    NOMBRES VARCHAR2(140),
    DOMICILIO VARCHAR2(500),
    ESTADO VARCHAR2(5), SECCION VARCHAR2(8), MUNICIPIO VARCHAR2(8),
    LOCALIDAD VARCHAR2(8), REGISTRO VARCHAR2(8),
    EMISION VARCHAR2(8), VIGENCIA VARCHAR2(20),
    MRZ CLOB, QR CLOB, PDF417 CLOB,
    FILE_SHA256 CHAR(64) UNIQUE NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
/
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_EXPEDIENTE (
    p_curp IN VARCHAR2, p_clave IN VARCHAR2, p_paterno IN VARCHAR2,
    p_materno IN VARCHAR2, p_nombres IN VARCHAR2, p_domicilio IN VARCHAR2,
    p_estado IN VARCHAR2, p_seccion IN VARCHAR2, p_municipio IN VARCHAR2,
    p_localidad IN VARCHAR2, p_registro IN VARCHAR2, p_emision IN VARCHAR2,
    p_vigencia IN VARCHAR2, p_mrz IN CLOB, p_qr IN CLOB,
    p_pdf417 IN CLOB, p_sha256 IN CHAR
) AS
BEGIN
    -- INSERT simple: un hash repetido viola la UNIQUE y produce ORA-00001, que la aplicación
    -- informa como "duplicado" (en lugar de ignorarlo en silencio). La transacción la controla Python.
    INSERT INTO INE_EXPEDIENTES_DEMO (
        CURP, CLAVE_ELECTOR, APELLIDO_PATERNO, APELLIDO_MATERNO, NOMBRES,
        DOMICILIO, ESTADO, SECCION, MUNICIPIO, LOCALIDAD, REGISTRO,
        EMISION, VIGENCIA, MRZ, QR, PDF417, FILE_SHA256
    ) VALUES (
        p_curp, p_clave, p_paterno, p_materno, p_nombres,
        p_domicilio, p_estado, p_seccion, p_municipio, p_localidad,
        p_registro, p_emision, p_vigencia, p_mrz, p_qr, p_pdf417, p_sha256
    );
END;
